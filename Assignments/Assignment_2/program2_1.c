#include<stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
// Function Name :  Display
// Description :    It is used to display '*' on screen using while loop
// Input :          Integer
// Output :         Pattern
// Author :         Poonam Narayan Palkar     
// Date :           15/10/2025
//
/////////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    int iCnt = 0;

    // Updater

    while(iCnt < iNo)
    {
        printf(" * ");
        iCnt++;
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
// Entry point function of the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number :\n ");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}