#include<stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
// Function Name :  Accept
// Description :    Display '*' on screen for given number of times
// Input :          Integer
// Output :         Pattern
// Author :         Poonam Narayan Palkar     
// Date :           15/10/2025
//
/////////////////////////////////////////////////////////////////////////////////////////////////

void Accept(int iNo)
{
    int iCnt = 0;
    
    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("* ");
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////
//
// Entry point function of the application
//
////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    
    printf("Enter number : \n");
    scanf("%d",&iValue);

    Accept(iValue);

    return 0;
}

